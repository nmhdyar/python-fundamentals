"""
فصل ۰۲.۴ — فیلترکردن با شرط‌ها

نکته‌های کلیدی:
- عملگر باقی‌مانده (%) باقیمانده تقسیم را برمی‌گرداند.
- اگر number % 2 == 0 باشد، عدد زوج است.
- اگر number % 2 != 0 باشد، عدد فرد است.
- شرط داخل حلقه تعیین می‌کند کدام اعضا پردازش شوند.
- range() عدد صحیح تولید می‌کند؛ نوع متغیر حلقه به‌صورت خودکار تشخیص داده می‌شود.
"""

# مثال ۱: چاپ اعداد زوج از ۱ تا ۲۰
start: int = 1
stop: int = 21

for number in range(start, stop):
    if number % 2 == 0:
        print("زوج:", number)

print("\n" + "-" * 40 + "\n")

# مثال ۲: چاپ اعداد فرد از ۱ تا ۱۵
for number in range(1, 16):
    if number % 2 != 0:
        print("فرد:", number)
