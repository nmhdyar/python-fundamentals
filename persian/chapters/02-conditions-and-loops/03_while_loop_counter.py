"""
فصل ۰۲.۳ — حلقه while

نکته‌های کلیدی:
- حلقه while تا زمانی تکرار می‌شود که شرط آن True باشد.
- وضعیت متغیری را که شرط به آن وابسته است به‌روزرسانی کن.
- مطمئن شو شرط توقف حلقه قابل دسترسی است.
"""

# مثال ۱: شمارش از ۱ تا ۵
count: int = 1

while count <= 5:
    print("شمارنده:", count)
    count += 1

print("\n" + "-" * 40 + "\n")

# مثال ۲: تکرار تا رسیدن به مقدار هدف
target: int = 4
guess: int = 0

while guess != target:
    guess += 1
    print("حدس فعلی:", guess)

print("به مقدار هدف رسیدیم!")

# اگر guess به‌روزرسانی نشود، ممکن است حلقه بی‌نهایت اجرا شود.
