"""
فصل ۰۲.۶ — شمارنده‌ها و انباره‌ها

نکته‌های کلیدی:
- شمارنده تعداد رخدادها را پیگیری می‌کند.
- انباره نتیجه‌ای را نگه می‌دارد که در طول تکرارها به‌روزرسانی می‌شود.
- این متغیرها را پیش از ورود به حلقه مقداردهی اولیه کن.
- برای شمارنده‌ها و انباره‌های عدد صحیح از Type Hint نوع int استفاده کن.
"""

# مثال ۱: محاسبه مجموع اعداد ۱ تا ۱۰۰
total: int = 0

for number in range(1, 101):
    total += number

print("مجموع اعداد ۱ تا ۱۰۰:", total)

print("\n" + "-" * 40 + "\n")

# مثال ۲: شمارش اعداد بخش‌پذیر بر ۳
divisible_count: int = 0

for number in range(1, 31):
    if number % 3 == 0:
        divisible_count += 1

print("تعداد اعداد بخش‌پذیر بر ۳:", divisible_count)
