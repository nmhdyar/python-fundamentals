"""
فصل ۰۲.۸ — خروجی شرطی با حلقه‌های تو در تو

نکته‌های کلیدی:
- هر تکرار حلقه‌های تو در تو یک اندیس سطر و یک اندیس ستون دارد.
- وقتی از range(number) استفاده می‌کنیم، اندیس‌ها از صفر شروع می‌شوند.
- ترکیب اندیس‌ها با عملگر باقی‌مانده می‌تواند الگوهای تکرارشونده بسازد.
- ابعاد را با int مشخص کن؛ نوع اندیس‌های حلقه به‌صورت خودکار تشخیص داده می‌شود.
"""

rows: int = 6
columns: int = 8

for row in range(rows):
    for column in range(columns):
        if (row + column) % 2 == 0:
            print("*", end=" ")
        else:
            print(" ", end=" ")
    print()

# تعداد سطرها و ستون‌ها را تغییر بده.
