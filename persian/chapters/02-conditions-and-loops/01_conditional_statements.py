"""
فصل ۰۲.۱ — ساختارهای شرطی

نکته‌های کلیدی:
- if یک بلوک را زمانی اجرا می‌کند که شرط آن True باشد.
- elif شرط دیگری را بررسی می‌کند، اگر شاخه‌های قبلی اجرا نشده باشند.
- else حالت‌های باقی‌مانده را پوشش می‌دهد.
- شرط‌ها از بالا به پایین بررسی می‌شوند.
"""

# مثال ۱: دسته‌بندی افراد بر اساس سن
age: int = 20

if age < 0:
    print("سن نامعتبر است.")
elif age < 13:
    print("کودک")
elif age < 18:
    print("نوجوان")
else:
    print("بزرگسال")

print("\n" + "-" * 40 + "\n")

# مثال ۲: اعتبارسنجی نمره و تعیین نتیجه
score: int = 87

if not 0 <= score <= 100:
    print("نمره نامعتبر است.")
elif score >= 90:
    print("نمره: A")
elif score >= 80:
    print("نمره: B")
elif score >= 70:
    print("نمره: C")
else:
    print("نیاز به تلاش بیشتر")

